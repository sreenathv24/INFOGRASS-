package javacode.maincode;

public class Wrapperclass {
    public static void main(String[] args) {
        Integer obj1 = 50;   // autoboxing
        int value = obj1;   // unboxing
        int number = 123;

        System.out.println("Autoboxing obj1" + obj1);
        System.out.println("unboxing value" + value);
        System.out.println("parse" + number);

    }
}
